import { readFile, readdir, writeFile, mkdir } from "node:fs/promises";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { deflateRawSync } from "node:zlib";
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const folder = resolve(root, "extensions/newvox-meet");
const names = (await readdir(folder))
  .filter((n) => /\.(js|html|css|json|md)$/.test(n))
  .sort();
const crc32 = (buffer) => {
  let crc = 0xffffffff;
  for (const b of buffer) {
    crc ^= b;
    for (let n = 0; n < 8; n++) crc = (crc >>> 1) ^ (crc & 1 ? 0xedb88320 : 0);
  }
  return (crc ^ 0xffffffff) >>> 0;
};
const files = [],
  directory = [];
let offset = 0;
for (const name of names) {
  const raw = await readFile(resolve(folder, name)),
    data = deflateRawSync(raw),
    path = Buffer.from("newvox-reunioes/" + name),
    crc = crc32(raw);
  const h = Buffer.alloc(30);
  h.writeUInt32LE(0x04034b50, 0);
  h.writeUInt16LE(20, 4);
  h.writeUInt16LE(8, 8);
  h.writeUInt32LE(crc, 14);
  h.writeUInt32LE(data.length, 18);
  h.writeUInt32LE(raw.length, 22);
  h.writeUInt16LE(path.length, 26);
  const c = Buffer.alloc(46);
  c.writeUInt32LE(0x02014b50, 0);
  c.writeUInt16LE(20, 4);
  c.writeUInt16LE(20, 6);
  c.writeUInt16LE(8, 10);
  c.writeUInt32LE(crc, 16);
  c.writeUInt32LE(data.length, 20);
  c.writeUInt32LE(raw.length, 24);
  c.writeUInt16LE(path.length, 28);
  c.writeUInt32LE(offset, 42);
  files.push(h, path, data);
  directory.push(c, path);
  offset += h.length + path.length + data.length;
}
const cd = Buffer.concat(directory),
  end = Buffer.alloc(22);
end.writeUInt32LE(0x06054b50, 0);
end.writeUInt16LE(names.length, 8);
end.writeUInt16LE(names.length, 10);
end.writeUInt32LE(cd.length, 12);
end.writeUInt32LE(offset, 16);
const archive = Buffer.concat([...files, cd, end]);
await mkdir(resolve(root, "artifacts"), { recursive: true });
const version = JSON.parse(
  await readFile(resolve(folder, "manifest.json"), "utf8"),
).version;
await writeFile(
  resolve(root, `artifacts/newvox-reunioes-${version}.zip`),
  archive,
);
await writeFile(
  resolve(root, "supabase/functions/_shared/meeting-extension-archive.ts"),
  `// Generated by scripts/package-meeting-extension.mjs. Source: extensions/newvox-meet. No secrets.\nexport const extensionArchive = "${archive.toString("base64")}";\n`,
);
console.log(
  JSON.stringify({
    files: names.length,
    bytes: archive.length,
    version: JSON.parse(
      await readFile(resolve(folder, "manifest.json"), "utf8"),
    ).version,
  }),
);
